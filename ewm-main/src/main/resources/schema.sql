CREATE TABLE IF NOT EXISTS categories (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
name TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS users (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
email TEXT NOT NULL UNIQUE,
name TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS events (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
annotation TEXT NOT NULL,
category_id BIGINT NOT NULL,
description TEXT NOT NULL,
event_date TIMESTAMP NOT NULL,
initiator_id BIGINT NOT NULL,
lat REAL NOT NULL,
lon REAL NOT NULL,
paid BOOLEAN DEFAULT false,
participant_limit INTEGER DEFAULT 0,
request_moderation BOOLEAN DEFAULT true,
state TEXT NOT NULL,
created_on TIMESTAMP NOT NULL,
published_on TIMESTAMP,
title TEXT NOT NULL,
CONSTRAINT fk_event_category_id FOREIGN KEY (category_id) REFERENCES categories(id) ON DELETE RESTRICT,
CONSTRAINT fk_event_initiator_id FOREIGN KEY (initiator_id) REFERENCES users(id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS requests(
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
event_id BIGINT NOT NULL,
requester_id BIGINT NOT NULL,
status TEXT NOT NULL,
created TIMESTAMP NOT NULL,
CONSTRAINT fk_event_id_requests FOREIGN KEY (event_id) REFERENCES events(id) ON DELETE RESTRICT,
CONSTRAINT fk_requester_id_requests FOREIGN KEY (requester_id) REFERENCES users(id) ON DELETE CASCADE,
CONSTRAINT event_requester_unique UNIQUE (event_id, requester_id)
);

CREATE TABLE IF NOT EXISTS compilations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pinned BOOLEAN NOT NULL DEFAULT false,
    title TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS compilations_events (
    compilation_id BIGINT NOT NULL,
    event_id BIGINT NOT NULL,
    CONSTRAINT fk_ce_compilation FOREIGN KEY (compilation_id) REFERENCES compilations(id) ON DELETE CASCADE,
    CONSTRAINT fk_ce_event FOREIGN KEY (event_id) REFERENCES events(id) ON DELETE CASCADE,
    PRIMARY KEY (compilation_id, event_id)
);